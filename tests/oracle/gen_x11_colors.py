"""Generates src/Aardvark.PixImage.PixCodec/Xpm/X11Colors.cs, the colour name table XPM files refer to, from X.Org's
rgb.txt (MIT/X licence, see THIRD-PARTY-NOTICES.md). Names are stored lower case without spaces, as they are looked up.

usage: python3 gen_x11_colors.py [/usr/share/X11/rgb.txt]
"""
import os
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/X11/rgb.txt'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'Aardvark.PixImage.PixCodec', 'Xpm', 'X11Colors.cs')


def main():
    names = {}
    with open(SRC) as f:
        for line in f:
            if line.startswith('!') or not line.strip():
                continue
            r, g, b, *name = line.split()
            key = ''.join(name).lower()
            v = (int(r) << 16) | (int(g) << 8) | int(b)
            if names.setdefault(key, v) != v:
                raise SystemExit(f'conflicting entries for {key}')
    items = sorted(names.items())
    lines = []
    cur = ''
    for k, v in items:
        e = f'{k}={v:06x};'
        if len(cur) + len(e) > 100:
            lines.append(cur)
            cur = ''
        cur += e
    lines.append(cur)
    body = '\n'.join(f'            + "{l}"' for l in lines)
    with open(OUT, 'w', newline='\n') as f:
        f.write(f'''// Generated by tests/oracle/gen_x11_colors.py from X.Org's rgb.txt ({len(items)} names); see THIRD-PARTY-NOTICES.md.
using System;
using System.Collections.Generic;

namespace Aardvark.ImageCodecs.XpmImpl
{{
    internal static class X11Colors
    {{
        // name=rrggbb; with names in lower case and without spaces
        const string Table = ""
{body};

        static Dictionary<string, int>? map;

        /// <summary>The colour (0xRRGGBB) of an X11 colour name (case and spaces ignored), or -1.</summary>
        public static int Lookup(ReadOnlySpan<char> name)
        {{
            var m = map ??= Build();
            Span<char> key = stackalloc char[Math.Min(name.Length, 64)];
            int n = 0;
            foreach (char c in name)
            {{
                if (c == ' ' || c == '\\t') continue;
                if (n == key.Length) return -1;
                key[n++] = char.ToLowerInvariant(c);
            }}
            return m.TryGetValue(new string(key.Slice(0, n)), out int v) ? v : -1;
        }}

        static Dictionary<string, int> Build()
        {{
            var d = new Dictionary<string, int>({len(items)});
            foreach (var e in Table.Split(';', StringSplitOptions.RemoveEmptyEntries))
            {{
                int eq = e.IndexOf('=');
                d[e.Substring(0, eq)] = Convert.ToInt32(e.Substring(eq + 1), 16);
            }}
            return d;
        }}
    }}
}}
''')
    print(f'{len(items)} names -> {OUT}')


if __name__ == '__main__':
    main()

# Generates src/Aardvark.PixImage.PixCodec/Avif/Av1Tables.Spec.cs from the text of the AV1 specification (dev-time tool;
# the specification is not committed). Get the text with
#   curl -sSLo av1-spec.html https://aomediacodec.github.io/av1-spec/   (2023-05-25, with errata)
#   lynx -dump -nolist -width=200 av1-spec.html > av1-spec.txt
# and run  python3 gen_av1_tables.py av1-spec.txt ../../src/Aardvark.PixImage.PixCodec/Avif/Av1Tables.Spec.cs
import re, sys
txt = open(sys.argv[1], encoding='utf-8').read()
out = sys.argv[2]
lines = txt.split('\n')
C = {}
# the constants of section 3 (Symbols and abbreviated terms): "NAME  value  description" rows, first one wins
for l in lines:
    m = re.match(r'^\s+([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+)\s+(-?\d+(?:\s*<<\s*\d+)?)\s+[A-Z]', l)
    if m and m.group(1) not in C: C[m.group(1)] = int(eval(m.group(2)))
# names the tables use that the symbol list does not give a plain value (enums, products)
C.update(MAX_TILE_AREA=4096 * 2304, IDTX=9, SUBPEL_MASK=15, IDENTITY=0, TRANSLATION=1, ROTZOOM=2, AFFINE=3, SIMPLE=0, OBMC=1, LOCALWARP=2)
C['SUPERRES_FILTER_SHIFTS'] = 64; C['MAX_TX_DEPTH'] = 2; C['REFMVS_LIMIT'] = (1<<12)-1
blocks = ['4X4','4X8','8X4','8X8','8X16','16X8','16X16','16X32','32X16','32X32','32X64','64X32','64X64','64X128','128X64','128X128','4X16','16X4','8X32','32X8','16X64','64X16']
for i,b in enumerate(blocks): C['BLOCK_'+b] = i
C['BLOCK_INVALID'] = 22
txs = ['4X4','8X8','16X16','32X32','64X64','4X8','8X4','8X16','16X8','16X32','32X16','32X64','64X32','4X16','16X4','8X32','32X8','16X64','64X16']
for i,t in enumerate(txs): C['TX_'+t] = i
modes = ['DC_PRED','V_PRED','H_PRED','D45_PRED','D135_PRED','D113_PRED','D157_PRED','D203_PRED','D67_PRED','SMOOTH_PRED','SMOOTH_V_PRED','SMOOTH_H_PRED','PAETH_PRED','UV_CFL_PRED']
for i,m in enumerate(modes): C[m] = i
for i,w in enumerate(['WEDGE_HORIZONTAL','WEDGE_VERTICAL','WEDGE_OBLIQUE27','WEDGE_OBLIQUE63','WEDGE_OBLIQUE117','WEDGE_OBLIQUE153']): C[w] = i
for i,r in enumerate(['RESTORE_NONE','RESTORE_WIENER','RESTORE_SGRPROJ','RESTORE_SWITCHABLE']): C[r] = i
for i,r in enumerate(['INTRA_FRAME','LAST_FRAME','LAST2_FRAME','LAST3_FRAME','GOLDEN_FRAME','BWDREF_FRAME','ALTREF2_FRAME','ALTREF_FRAME']): C[r] = i
pat = re.compile(r'^\s*([A-Z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)+)\s*((?:\[[^\]]*\]\s*)+)=\s*(\{.*)?$')
def ev(t):
    t = t.strip()
    if re.fullmatch(r'-?\d+', t.replace(' ', '')): return int(t.replace(' ', ''))
    return int(eval(re.sub(r'[A-Z][A-Z0-9_]*', lambda m: str(C[m.group(0)]), t)))
tables = {}
i = 0
while i < len(lines):
    m = pat.match(lines[i])
    if m and (m.group(3) is not None or (i+1 < len(lines) and lines[i+1].strip().startswith('{'))):
        name = m.group(1); dims = re.findall(r'\[([^\]]*)\]', m.group(2))
        rest = lines[i][lines[i].index('=')+1:]
        depth = 0; started = False; outc = []; j = i
        while True:
            for ch in rest:
                if ch == '{': depth += 1; started = True
                if started: outc.append(ch)
                if ch == '}':
                    depth -= 1
                    if depth == 0 and started: break
            if started and depth == 0: break
            j += 1; rest = lines[j] + '\n'
        body = ''.join(outc)
        body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
        body = re.sub(r'//[^\n]*', '', body)
        body = body.replace('{', ',').replace('}', ',')
        # the spec misses a comma in Split_Tx_Size
        body = re.sub(r'(TX_\d+X\d+)\s*\n\s*(TX_)', r'\1,\n\2', body)
        vals = [ev(t) for t in body.split(',') if t.strip()]
        try:
            n = 1
            for d in dims: n *= ev(d)
        except Exception: n = None
        if name not in tables: tables[name] = (dims, vals, n)
        i = j + 1
        continue
    i += 1
def cs(name): return name.replace('_', '')
w = open(out, 'w')
w.write('// <auto-generated>\n// Constant tables of the AV1 Bitstream & Decoding Process Specification (normative content), extracted from the\n// specification text by tests/oracle/gen_av1_tables.py. Do not edit.\n// </auto-generated>\nusing System;\n\nnamespace Aardvark.ImageCodecs.Av1\n{\n    internal static partial class Av1Tables\n    {\n')
skip = {'Tx_Type_Intra_Inv_Set1','Tx_Type_Intra_Inv_Set2','Tx_Type_Inter_Inv_Set1','Tx_Type_Inter_Inv_Set2','Tx_Type_Inter_Inv_Set3'}
for name, (dims, vals, n) in tables.items():
    if n is not None and n != len(vals):
        print('COUNT MISMATCH', name, dims, n, len(vals), file=sys.stderr)
    lo, hi = min(vals), max(vals)
    t = 'byte' if lo >= 0 and hi < 256 else 'sbyte' if lo >= -128 and hi < 128 else 'ushort' if lo >= 0 and hi < 65536 else 'short' if lo >= -32768 and hi < 32768 else 'int'
    if name.startswith('Default_') and name.endswith('_Cdf'): t = 'ushort'
    dimtxt = "][".join(d.strip() for d in dims).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    w.write(f'        /// <summary>{name}[{dimtxt}]</summary>\n')
    w.write(f'        public static ReadOnlySpan<{t}> {cs(name)} => new {t}[] {{')
    for k, v in enumerate(vals):
        if k % 24 == 0: w.write('\n            ')
        w.write(f'{v}, ')
    w.write('\n        };\n\n')
w.write('    }\n}\n')
w.close()
print(len(tables), 'tables')
